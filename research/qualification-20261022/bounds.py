"""Exact-rational Taylor enclosures and forward-error certificate; no libm oracle."""
from fractions import Fraction as F
from pathlib import Path
import argparse
import json
import math
import subprocess

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
DEGREE = 14
TERMS = 100
RADIUS = F(1, 4)
U = F(1, 2**53)
ETA = F(1, 2**1075)


def coefficient(c, j, k):
    """Enclose phi_k^(j)(c)/j! by 100 rational terms plus geometric tail."""
    term = F(1, math.factorial(j + k))
    total = term
    for m in range(1, TERMS):
        term *= c * F(m + j, m * (m + j + k))
        total += term
    first = abs(term * c * F(TERMS + j, TERMS * (TERMS + j + k)))
    # Every subsequent absolute ratio is <= abs(c)/(TERMS+1).
    tail = first / (1 - abs(c) / (TERMS + 1))
    return total - tail, total + tail


def exp_upper(x):
    assert x >= 0
    term = total = F(1)
    for m in range(1, TERMS):
        term *= x / m
        total += term
    return total + term * x / TERMS / (1 - x / (TERMS + 1))


def power2(n):
    return F(2**n) if n >= 0 else F(1, 2**-n)


def floor_log2(x):
    assert x > 0
    e = x.numerator.bit_length() - x.denominator.bit_length()
    return e if power2(e) <= x else e - 1


def upper_hex(x):
    return math.nextafter(float(x), math.inf).hex()


def rounded_coefficient(lo, hi):
    a = float((lo + hi) / 2)
    aq = F(a)
    # Strict containment in the nearest-even rounding cell; no midpoint ties.
    assert (F(math.nextafter(a, -math.inf)) + aq) / 2 < lo
    assert hi < (aq + F(math.nextafter(a, math.inf))) / 2
    return a


def make_certificate():
    rows = []
    tables = []
    for k in (1, 2, 3):
        table = []
        for center_index in range(-8, 9):
            c = F(center_index, 2)
            intervals = [coefficient(c, j, k) for j in range(DEGREE + 1)]
            coeff = [rounded_coefficient(*ab) for ab in intervals]
            table.append(coeff)
            errors = [max(abs(F(a)-lo), abs(F(a)-hi))
                      for a, (lo, hi) in zip(coeff, intervals)]
            v, error = abs(F(coeff[-1])), errors[-1]
            for j in range(DEGREE-1, -1, -1):
                multiply_error = U*v*RADIUS + ETA
                w = v*RADIUS + multiply_error
                add_error = U*(w + abs(F(coeff[j]))) + ETA
                error = RADIUS*error + multiply_error + errors[j] + add_error
                v = w + abs(F(coeff[j])) + add_error
            tail = (exp_upper(max(c + RADIUS, F(0))) * RADIUS**(DEGREE+1)
                    / math.factorial(DEGREE+k+1))
            error += tail
            lower = coefficient(max(F(-4), c-RADIUS), 0, k)[0]
            upper = coefficient(min(F(4), c+RADIUS), 0, k)[1]
            reference_rounding = power2(floor_log2(upper)-53)
            minimum_spacing = power2(floor_log2(lower-error-reference_rounding)-52)
            ulp_bound = math.ceil((error + reference_rounding)/minimum_spacing)
            assert v < 100 and lower-error > 0
            assert ulp_bound <= 16, (k, c, ulp_bound)
            rows.append({"order": k, "center_hex": float(c).hex(),
                         "coefficient_hex": [x.hex() for x in coeff],
                         "absolute_error_upper_hex": upper_hex(error),
                         "taylor_remainder_upper_hex": upper_hex(tail),
                         "integer_ulp_bound": ulp_bound})
        tables.append(table)
    certificate = {"degree": DEGREE, "terms": TERMS, "domain": [-4, 4],
                   "radius": "0x1.0000000000000p-2", "rows": rows,
                   "max_integer_ulp_bound": max(r["integer_ulp_bound"] for r in rows),
                   "status": "author-derived bound; independent review pending"}
    return certificate, tables


def c_source(tables):
    nested = lambda xs: "{" + ",".join(xs) + "}"
    data = nested([nested([nested([a.hex() for a in row]) for row in tab]) for tab in tables])
    horner = "\n".join(f"p = p*y + a[{j}];" for j in range(DEGREE-1, -1, -1))
    return f'''/* Generated by bounds.py; degree and partition fixed before evaluation. */
#include <fenv.h>
#include <float.h>
#include "../../src/kernels.c"
_Static_assert(DBL_MANT_DIG == 53 && DBL_MAX_EXP == 1024, "binary64 required");
static const double coefficients[3][17][{DEGREE+1}] = {data};
int qualified_environment(void) {{
    volatile double tiny=0x0.0000000000001p-1022, one=1., half=0x1p-53;
    return fegetround()==FE_TONEAREST && tiny+tiny==0x0.0000000000002p-1022
        && one+half==one;
}}
static double piece(double x, int k) {{
    if (!isfinite(x) || fabs(x)>4. || k<1 || k>3) return NAN;
    double center=0.5*nearbyint(2.*x);
    int idx=(int)(2.*center)+8;
    double y=x-center;
    const double *a=coefficients[k-1][idx];
    double p=a[{DEGREE}];
    {horner}
    return p;
}}
static double p1(double x) {{return piece(x,1);}}
static double p2(double x) {{return piece(x,2);}}
static double p3(double x) {{return piece(x,3);}}
double qualified(const double *x, size_t n, int k, int mode, int reps, double *out) {{
    double (*f)(double)=0;
    if(k==1) {{double (*fs[])(double)={{f1_0,f1_9,p1,f1_2,f1_1}}; if(mode>=0&&mode<5)f=fs[mode];}}
    if(k==2) {{double (*fs[])(double)={{f2_0,f2_23,p2,f2_2,f2_1}}; if(mode>=0&&mode<5)f=fs[mode];}}
    if(k==3) {{double (*fs[])(double)={{f3_0,f3_30,p3,f3_2,f3_1}}; if(mode>=0&&mode<5)f=fs[mode];}}
    if(!f || !qualified_environment())return NAN;
    double sum=0.;
    for(int r=0;r<reps;r++) for(size_t i=0;i<n;i++){{out[i]=f(x[i]);sum+=out[i];}}
    return sum;
}}
'''


def build(verify=False):
    cert, tables = make_certificate()
    rendered = json.dumps(cert, indent=2) + "\n"
    source = c_source(tables)
    if verify:
        assert (HERE/"certificate.json").read_text() == rendered, "certificate mismatch"
        assert (HERE/"qualified.c").read_text() == source, "candidate mismatch"
    else:
        (HERE/"certificate.json").write_text(rendered)
        (HERE/"qualified.c").write_text(source)
    (ROOT/"build").mkdir(exist_ok=True)
    command = ["clang", "-O3", "-std=c11", "-fno-fast-math", "-ffp-contract=off",
               "-shared", "-fPIC", str(HERE/"qualified.c"), "-o", str(ROOT/"build/qualified.dylib")]
    subprocess.run(command, check=True)
    print(json.dumps({"certificate_verified": verify, "max_integer_ulp_bound": cert["max_integer_ulp_bound"],
                      "coefficient_table_bytes": 3*17*(DEGREE+1)*8, "compiler_command": command}))


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--verify", action="store_true")
    build(parser.parse_args().verify)
